/**
 * backend/tests/webhookHmac.test.ts
 *
 * Issue #1420 — [Test] Backend: unit tests for webhook HMAC signing and verification
 *
 * All 6 acceptance-criteria test cases:
 *   1. Sign payload:  correct HMAC-SHA256 signature generated
 *   2. Verify signature: valid signature accepted
 *   3. Verify signature: tampered payload rejected
 *   4. Verify signature: wrong secret rejected
 *   5. Header format: X-SorobanPay-Signature header present (sha256= prefix)
 *   6. Timing-safe comparison used (not vulnerable to timing attacks)
 *
 * Test fixture: known payload + secret + expected signature (golden vector).
 * The expected signature is computed at module load time from Node's built-in
 * `crypto` so the test is self-contained and never needs hard-coded hex strings
 * that could drift if the algorithm changes.
 */

import * as crypto from 'crypto';
import { signPayload, verifyWebhookSignature } from '../src/services/webhookSignature';

// ─── Shared golden-vector fixture ─────────────────────────────────────────────

const FIXTURE_PAYLOAD = '{"event":"payment.executed","amount":"1000000","subscriberId":"GABC1234"}';
const FIXTURE_SECRET  = 'whsec_test_1420_secret_key';

/**
 * Compute the reference expected signature once at module-init time.
 * This is the single source of truth for all assertions in this file.
 */
const FIXTURE_EXPECTED_SIGNATURE = (() => {
  const hex = crypto
    .createHmac('sha256', FIXTURE_SECRET)
    .update(FIXTURE_PAYLOAD)
    .digest('hex');
  return `sha256=${hex}`;
})();

// ─── 1 + 5. Sign payload & header format ─────────────────────────────────────

describe('signPayload — correct HMAC-SHA256 signature generated (#1420 TC-1, TC-5)', () => {
  it('TC-1: generates the correct HMAC-SHA256 signature for the known fixture', () => {
    const result = signPayload(FIXTURE_PAYLOAD, FIXTURE_SECRET);
    expect(result).toBe(FIXTURE_EXPECTED_SIGNATURE);
  });

  it('TC-5: signature has the "sha256=" prefix (X-SorobanPay-Signature header format)', () => {
    const result = signPayload(FIXTURE_PAYLOAD, FIXTURE_SECRET);
    expect(result).toMatch(/^sha256=[a-f0-9]{64}$/);
  });

  it('signature is deterministic — same inputs always produce the same output', () => {
    const sig1 = signPayload(FIXTURE_PAYLOAD, FIXTURE_SECRET);
    const sig2 = signPayload(FIXTURE_PAYLOAD, FIXTURE_SECRET);
    expect(sig1).toBe(sig2);
  });

  it('different payloads produce different signatures', () => {
    const sig1 = signPayload(FIXTURE_PAYLOAD, FIXTURE_SECRET);
    const sig2 = signPayload(FIXTURE_PAYLOAD + ' ', FIXTURE_SECRET);
    expect(sig1).not.toBe(sig2);
  });

  it('handles an empty payload — returns a valid sha256= prefixed digest', () => {
    const result = signPayload('', FIXTURE_SECRET);
    expect(result).toMatch(/^sha256=[a-f0-9]{64}$/);
  });

  it('handles a large JSON payload (>10 KB) deterministically', () => {
    const large = JSON.stringify({
      event: 'bulk.processed',
      items: Array.from({ length: 200 }, (_, i) => ({ id: i, data: 'payload-data-block' })),
    });
    const sig1 = signPayload(large, FIXTURE_SECRET);
    const sig2 = signPayload(large, FIXTURE_SECRET);
    expect(sig1).toBe(sig2);
    expect(sig1).toMatch(/^sha256=[a-f0-9]{64}$/);
  });
});

// ─── 2. Verify signature: valid signature accepted ────────────────────────────

describe('verifyWebhookSignature — valid signature accepted (#1420 TC-2)', () => {
  it('TC-2: returns true for a correctly signed payload (fixture)', () => {
    expect(
      verifyWebhookSignature(FIXTURE_PAYLOAD, FIXTURE_EXPECTED_SIGNATURE, FIXTURE_SECRET),
    ).toBe(true);
  });

  it('accepts a freshly signed payload generated by signPayload', () => {
    const payload = JSON.stringify({ event: 'subscription.created', ts: 1700000000 });
    const sig = signPayload(payload, FIXTURE_SECRET);
    expect(verifyWebhookSignature(payload, sig, FIXTURE_SECRET)).toBe(true);
  });

  it('accepts an empty payload with its correct signature', () => {
    const sig = signPayload('', FIXTURE_SECRET);
    expect(verifyWebhookSignature('', sig, FIXTURE_SECRET)).toBe(true);
  });

  it('accepts a unicode/multi-byte UTF-8 payload', () => {
    const payload = '{"merchant":"Café ☕ 🚀","currency":"€uro"}';
    const sig = signPayload(payload, FIXTURE_SECRET);
    expect(verifyWebhookSignature(payload, sig, FIXTURE_SECRET)).toBe(true);
  });
});

// ─── 3. Verify signature: tampered payload rejected ──────────────────────────

describe('verifyWebhookSignature — tampered payload rejected (#1420 TC-3)', () => {
  it('TC-3: returns false when a single digit is changed in the payload', () => {
    const tampered = FIXTURE_PAYLOAD.replace('1000000', '9999999');
    expect(
      verifyWebhookSignature(tampered, FIXTURE_EXPECTED_SIGNATURE, FIXTURE_SECRET),
    ).toBe(false);
  });

  it('returns false when a single byte is appended to the payload', () => {
    expect(
      verifyWebhookSignature(FIXTURE_PAYLOAD + '\x00', FIXTURE_EXPECTED_SIGNATURE, FIXTURE_SECRET),
    ).toBe(false);
  });

  it('returns false when the last byte is removed from the payload', () => {
    expect(
      verifyWebhookSignature(FIXTURE_PAYLOAD.slice(0, -1), FIXTURE_EXPECTED_SIGNATURE, FIXTURE_SECRET),
    ).toBe(false);
  });

  it('returns false for a completely different payload', () => {
    expect(
      verifyWebhookSignature('totally different body', FIXTURE_EXPECTED_SIGNATURE, FIXTURE_SECRET),
    ).toBe(false);
  });
});

// ─── 4. Verify signature: wrong secret rejected ───────────────────────────────

describe('verifyWebhookSignature — wrong secret rejected (#1420 TC-4)', () => {
  it('TC-4: returns false when the secret is entirely wrong', () => {
    expect(
      verifyWebhookSignature(FIXTURE_PAYLOAD, FIXTURE_EXPECTED_SIGNATURE, 'wrong_secret'),
    ).toBe(false);
  });

  it('returns false when the secret is a one-character variation', () => {
    const almostRight = FIXTURE_SECRET.slice(0, -1) + 'X';
    expect(
      verifyWebhookSignature(FIXTURE_PAYLOAD, FIXTURE_EXPECTED_SIGNATURE, almostRight),
    ).toBe(false);
  });

  it('returns false when the secret is empty', () => {
    expect(
      verifyWebhookSignature(FIXTURE_PAYLOAD, FIXTURE_EXPECTED_SIGNATURE, ''),
    ).toBe(false);
  });

  it('returns false for a truncated signature header', () => {
    const truncated = FIXTURE_EXPECTED_SIGNATURE.slice(0, -4);
    expect(verifyWebhookSignature(FIXTURE_PAYLOAD, truncated, FIXTURE_SECRET)).toBe(false);
  });

  it('returns false when the algorithm prefix is wrong (sha512= instead of sha256=)', () => {
    const rawHex = FIXTURE_EXPECTED_SIGNATURE.replace('sha256=', '');
    expect(verifyWebhookSignature(FIXTURE_PAYLOAD, `sha512=${rawHex}`, FIXTURE_SECRET)).toBe(false);
  });

  it('returns false when the signature header is missing the prefix entirely', () => {
    const rawHex = FIXTURE_EXPECTED_SIGNATURE.replace('sha256=', '');
    expect(verifyWebhookSignature(FIXTURE_PAYLOAD, rawHex, FIXTURE_SECRET)).toBe(false);
  });

  it('returns false when the signature header is empty', () => {
    expect(verifyWebhookSignature(FIXTURE_PAYLOAD, '', FIXTURE_SECRET)).toBe(false);
  });

  it('returns false when body is undefined (graceful guard)', () => {
    expect(
      verifyWebhookSignature(
        undefined as unknown as string,
        FIXTURE_EXPECTED_SIGNATURE,
        FIXTURE_SECRET,
      ),
    ).toBe(false);
  });
});

// ─── 6. Timing-safe comparison verified ──────────────────────────────────────

describe('verifyWebhookSignature — timing-safe comparison (#1420 TC-6)', () => {
  /**
   * The implementation uses Node's `crypto.timingSafeEqual` which compares
   * two equal-length buffers in constant time, preventing timing-oracle attacks.
   *
   * We verify this behavioural guarantee in two ways:
   *   (a) Spy on crypto.timingSafeEqual to confirm it is called for both valid
   *       and invalid signatures of equal byte length.
   *   (b) Confirm that a signature differing only in the last byte is still
   *       fully evaluated (not short-circuited) — i.e., returns `false` rather
   *       than throwing or skipping.
   */

  it('TC-6a: calls crypto.timingSafeEqual when verifying a correct signature', () => {
    const spy = jest.spyOn(crypto, 'timingSafeEqual');

    verifyWebhookSignature(FIXTURE_PAYLOAD, FIXTURE_EXPECTED_SIGNATURE, FIXTURE_SECRET);

    expect(spy).toHaveBeenCalledTimes(1);
    spy.mockRestore();
  });

  it('TC-6b: calls crypto.timingSafeEqual even when the signature is wrong (no early exit)', () => {
    const spy = jest.spyOn(crypto, 'timingSafeEqual');

    // Build a wrong signature that has the exact same byte-length as the correct one
    const wrongSig = signPayload(FIXTURE_PAYLOAD, 'a_completely_different_secret_XYZ');
    expect(wrongSig.length).toBe(FIXTURE_EXPECTED_SIGNATURE.length); // same length → timingSafeEqual called

    verifyWebhookSignature(FIXTURE_PAYLOAD, wrongSig, FIXTURE_SECRET);

    expect(spy).toHaveBeenCalledTimes(1);
    spy.mockRestore();
  });

  it('TC-6c: returns false for a signature differing only in the first byte (full comparison)', () => {
    // Flip first hex character of the digest part
    const firstByteFlipped = FIXTURE_EXPECTED_SIGNATURE.replace(/sha256=(.)/, (_, c) =>
      `sha256=${c === 'a' ? 'b' : 'a'}`,
    );
    expect(verifyWebhookSignature(FIXTURE_PAYLOAD, firstByteFlipped, FIXTURE_SECRET)).toBe(false);
  });

  it('TC-6d: returns false for a signature differing only in the last byte (full comparison)', () => {
    // Flip last hex character of the digest
    const lastChar = FIXTURE_EXPECTED_SIGNATURE.at(-1)!;
    const lastByteFlipped =
      FIXTURE_EXPECTED_SIGNATURE.slice(0, -1) + (lastChar === 'a' ? 'b' : 'a');
    expect(verifyWebhookSignature(FIXTURE_PAYLOAD, lastByteFlipped, FIXTURE_SECRET)).toBe(false);
  });
});
